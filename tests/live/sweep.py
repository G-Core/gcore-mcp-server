"""Read-only sweep: call every argument-free read operation on a real account.

    uv run python -m tests.live.sweep            # writes reports/LIVE_SWEEP.md (git-ignored)

Every catalog operation that is classified ``read`` and needs no arguments
beyond the default project/region is called once through the same
``Dispatcher`` the MCP tools use. Failures are findings, not test failures:
they show where the SDK, the API or the account disagree. The report lists
each operation with its outcome.
"""

from __future__ import annotations

import asyncio
import json
import time
from collections import Counter
from pathlib import Path
from typing import Any

import gcore
from fastmcp.exceptions import ToolError

from gcore_mcp_server.catalog import Access, Catalog
from gcore_mcp_server.runtime import Dispatcher, SafetyPolicy
from gcore_mcp_server.runtime.scope import CloudScope

from .common import PROJECT_ID, REGION_ID, live_client

REPORT = Path(__file__).resolve().parents[2] / "reports" / "LIVE_SWEEP.md"
CONCURRENCY = 6
CALL_TIMEOUT = 45.0


def sweepable(catalog: Catalog) -> list[str]:
    """Read operations callable with no arguments (project/region default)."""
    names: list[str] = []
    for entry in catalog.entries:
        if entry.access is not Access.READ:
            continue
        if entry.name.endswith("_and_poll") or entry.name == "cloud.tasks.poll":
            continue
        if not entry.required_params:
            names.append(entry.name)
    return names


def classify_failure(message: str) -> str:
    for code in (
        "HTTP 400",
        "HTTP 401",
        "HTTP 403",
        "HTTP 404",
        "HTTP 405",
        "HTTP 409",
        "HTTP 422",
        "HTTP 429",
        "HTTP 5",
    ):
        if code in message:
            return code.replace("HTTP 5", "HTTP 5xx")
    if "timed out" in message or "TimeoutError" in message:
        return "timeout"
    if "validation" in message.lower() or "ValidationError" in message:
        return "response validation"
    return "other"


async def run_sweep() -> list[dict[str, Any]]:
    client = live_client()
    catalog = Catalog.from_client(client)
    policy = SafetyPolicy(read_only=True)
    # The same scope filling as the server: schemas make client_id (and
    # project/region) optional because this fills them in.
    dispatcher = Dispatcher(
        catalog, policy, max_result_chars=0, scope=CloudScope(client, policy.is_denied)
    )
    names = sweepable(catalog)
    sem = asyncio.Semaphore(CONCURRENCY)
    rows: list[dict[str, Any]] = []

    async def one(name: str) -> None:
        entry = catalog.by_name[name]
        async with sem:
            started = time.monotonic()
            try:
                data = await asyncio.wait_for(
                    dispatcher.call_raw(entry, {}), CALL_TIMEOUT
                )
                size = len(json.dumps(data, default=str))
                rows.append(
                    {
                        "name": name,
                        "ok": True,
                        "ms": int((time.monotonic() - started) * 1000),
                        "chars": size,
                    }
                )
            except (
                ToolError,
                asyncio.TimeoutError,
                gcore.GcoreError,
                Exception,
            ) as exc:  # noqa: BLE001
                msg = str(exc) or type(exc).__name__
                rows.append(
                    {
                        "name": name,
                        "ok": False,
                        "ms": int((time.monotonic() - started) * 1000),
                        "kind": classify_failure(
                            msg
                            if not isinstance(exc, asyncio.TimeoutError)
                            else "timed out"
                        ),
                        "error": msg.splitlines()[0][:220],
                    }
                )

    await asyncio.gather(*(one(n) for n in names))
    rows.sort(key=lambda r: r["name"])
    return rows


def write_report(rows: list[dict[str, Any]]) -> str:
    ok = [r for r in rows if r["ok"]]
    bad = [r for r in rows if not r["ok"]]
    kinds = Counter(r["kind"] for r in bad)
    by_service: dict[str, list[int]] = {}
    for r in rows:
        svc = r["name"].split(".")[0]
        by_service.setdefault(svc, [0, 0])
        by_service[svc][0 if r["ok"] else 1] += 1

    lines = [
        "# Live read-only sweep",
        "",
        f"Generated by `uv run python -m tests.live.sweep` on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}"
        f" against project {PROJECT_ID}, region {REGION_ID}, gcore SDK {gcore.__version__}.",
        "",
        "Every `read` operation that needs no arguments beyond the default project/region was",
        "called once through the server's dispatcher, in read-only mode. Failures are findings about the",
        "SDK, the API or the account - not necessarily bugs in this server.",
        "",
        f"**{len(ok)} / {len(rows)} succeeded.**",
        "",
        "| service | ok | failed |",
        "|---|---:|---:|",
        *[f"| {s} | {v[0]} | {v[1]} |" for s, v in sorted(by_service.items())],
        "",
        "Failures by kind: "
        + (", ".join(f"{k}: {n}" for k, n in kinds.most_common()) or "none"),
        "",
        "## Failures",
        "",
        "| operation | kind | first line of the error |",
        "|---|---|---|",
        *[
            f"| `{r['name']}` | {r['kind']} | {r['error'].replace('|', '/')} |"
            for r in bad
        ],
        "",
        "## Successes",
        "",
        "| operation | ms | result chars |",
        "|---|---:|---:|",
        *[f"| `{r['name']}` | {r['ms']} | {r['chars']} |" for r in ok],
        "",
    ]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(lines))
    return f"{len(ok)}/{len(rows)} ok; failures: {dict(kinds)}"


def main() -> None:
    rows = asyncio.run(run_sweep())
    print(write_report(rows))


if __name__ == "__main__":
    main()
